import pytest

from ades import sexVals

RA_DEC_TO_SEX_CASES = [
    (245.749999, 60,   '16 23       '),
    (245.749999, 6,    '16 23.0     '),
    (245.749999, 0.6,  '16 23.00    '),
    (245.749999, 1,    '16 23 00    '),
    (245.749999, 0.1,  '16 23 00.0  '),
    (245.749999, 1e-2, '16 23 00.00 '),
    (245.749999, 1e-3, '16 23 00.000'),
    (245.749999, 1e-4, '16 22 59.9998'),
    (245.749999, 1e-5, '16 22 59.99976'),
    (359.99998, 60,   '00 00       '),
    (359.99998, 6,    '00 00.0     '),
    (359.99998, 0.6,  '00 00.00    '),
    (359.99998, 1,    '00 00 00    '),
    (359.99998, 0.1,  '00 00 00.0  '),
    (359.99998, 1e-2, '00 00 00.00 '),
    (359.99998, 1e-3, '23 59 59.995'),
    (179.94, 60,  '12 00       '),
    (179.94, 6,   '11 59.8     '),
    (179.94, 0.6, '11 59.76    '),
    (179.94, 0.1, '11 59 45.6  '),
]


@pytest.mark.parametrize("ra_decimal,prec,expected_sexg", RA_DEC_TO_SEX_CASES)
def test_decRaToSexRa(ra_decimal, prec, expected_sexg):
    observed_sexg = sexVals.decRaToSexRa(ra_decimal, prec)
    assert observed_sexg == expected_sexg
